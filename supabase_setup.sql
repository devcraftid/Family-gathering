-- Jalankan di Supabase SQL Editor setelah meninjau kebijakan akses proyek.
-- Nomor kursi harus unik supaya tidak ada dua record untuk kursi yang sama.
create table if not exists public.kursi_bus (
  nomor_kursi integer primary key check (nomor_kursi between 1 and 59),
  nama text,
  no_hp text,
  updated_at timestamptz default now()
);
create table if not exists public.absensi (
  id bigint generated by default as identity primary key,
  nama text not null,
  waktu_absen timestamptz not null default now(),
  sumber text not null default 'Manual'
);
-- Isi 59 kursi kosong sekali saja; record kursi kosong membantu booking atomik.
insert into public.kursi_bus (nomor_kursi, nama)
select n, null from generate_series(1,59) as n
on conflict (nomor_kursi) do nothing;

alter table public.kursi_bus enable row level security;
alter table public.absensi enable row level security;

-- Public dapat melihat denah dan data nama peserta yang disimpan pada tabel ini.
-- Untuk produksi, pertimbangkan memisahkan data kontak agar nomor HP tidak publik.
drop policy if exists "public read bus seats" on public.kursi_bus;
create policy "public read bus seats" on public.kursi_bus for select to anon, authenticated using (true);

-- Booking publik hanya dapat mengubah kursi yang masih kosong menjadi terisi.
-- Kebijakan USING mengecek nilai lama baris, sehingga kursi terisi tidak bisa ditimpa.
drop policy if exists "public book empty seat" on public.kursi_bus;
create policy "public book empty seat" on public.kursi_bus
for update to anon, authenticated
using (nama is null or nama = '')
with check (nama is not null and length(trim(nama)) between 2 and 100);

-- Kehadiran: publik dapat menambahkan absensi, tetapi tidak membaca/menghapus data pribadi
-- kecuali kebijakan read terpisah memang diperlukan untuk dashboard admin.
drop policy if exists "public submit attendance" on public.absensi;
create policy "public submit attendance" on public.absensi
for insert to anon, authenticated with check (length(trim(nama)) between 2 and 100);

-- Untuk operasi admin UPDATE/DELETE/SELECT yang lebih luas, buat policy terpisah
-- berdasarkan auth.jwt() -> 'app_metadata' ->> 'role' = 'admin'.

-- Kebijakan tambahan untuk admin terautentikasi.
drop policy if exists "admin manage bus seats" on public.kursi_bus;
create policy "admin manage bus seats" on public.kursi_bus
for all to authenticated
using ((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin')
with check ((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin');

drop policy if exists "admin read attendance" on public.absensi;
create policy "admin read attendance" on public.absensi
for select to authenticated
using ((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin');

drop policy if exists "admin manage attendance" on public.absensi;
create policy "admin manage attendance" on public.absensi
for all to authenticated
using ((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin')
with check ((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin');
